/** Подобрать подсказки по названию дела */
export function suggestStepsOffline(title: string): { title: string; steps: string[] } {
  const t = title.toLowerCase();
  const hit = HINT_LIBRARY.find((g) => g.keywords.some((k) => t.includes(k)));
  if (hit) return { title: hit.title, steps: hit.steps };
  return { title: "Универсальный чек-лист", steps: GENERIC_STEPS };
}

/** Встроенные шаблоны для регулярных дел */
